import assert from 'node:assert/strict';
import {QuizRoom} from '../src/game/QuizRoom.ts';
import {Journey} from '../src/game/Journey.ts';
import {questionOrder} from '../src/game/QuestionOrder.ts';
const paper=Object.create(QuizRoom.prototype),j=new Journey();
const uv=(x,y)=>({x:x/1024,y:1-y/768});
assert.equal(paper.command(uv(750,700),j),'question');
assert.equal(j.openQuestion(),true);
assert.equal(paper.command(uv(450,700),j),'previous');
assert.equal(j.openQuestion(),true);
assert.equal(paper.command(uv(100,350),j),'prediction:0');
assert.equal(j.openQuestion(),false);
assert.equal(j.setPrediction(0),true);
assert.equal(j.openQuestion(),true);
assert.equal(j.observe('assembly'),true);
assert.equal(paper.command(uv(100,350),j),'reflection:0');
assert.equal(j.chooseReflection(0),true);
assert.equal(paper.command(uv(750,700),j),'finishReflection');
assert.equal(j.finishReflection(),true);
assert.equal(paper.command(uv(100,350),j),questionOrder(j.question.id)[0]);
assert.equal(j.answer(j.question.correct),'feedback');
assert.equal(paper.command(uv(750,700),j),'continueQuiz');
assert.equal(j.nextQuestion(),'next');
assert.equal(paper.command(uv(100,350),j),questionOrder(j.question.id)[0]);
assert.equal(paper.startDrag(uv(100,350),j),false);
assert.equal(j.awaiting,true);
console.log('3D study paper checks passed: pagination, prediction gate, reflection, quiz feedback, touch selection and preserved progress.');
